SELECT CASE WHEN YEAR(last_restock) < 2024 THEN 'before_2024' WHEN YEAR(last_restock) = 2024 THEN '2024' ELSE 'after_2024' END AS last_restock_cohort, MAX(last_restock) AS latest_last_restock, MAX(quantity) - MIN(quantity) AS quantity_range
FROM inventory
GROUP BY CASE WHEN YEAR(last_restock) < 2024 THEN 'before_2024' WHEN YEAR(last_restock) = 2024 THEN '2024' ELSE 'after_2024' END
HAVING MAX(quantity) - MIN(quantity) < 75
ORDER BY quantity_range DESC
