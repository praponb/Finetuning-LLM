SELECT
    event_type,
    CASE WHEN YEAR(event_time) < 2024 THEN 'before_2024' WHEN YEAR(event_time) = 2024 THEN '2024' ELSE 'after_2024' END AS event_cohort,
    SUM(duration_sec) AS total_duration_sec,
    COUNT(*) AS cnt
FROM web_events
GROUP BY event_type, CASE WHEN YEAR(event_time) < 2024 THEN 'before_2024' WHEN YEAR(event_time) = 2024 THEN '2024' ELSE 'after_2024' END
