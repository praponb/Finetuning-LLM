from pyspark.sql import functions as F

joined_ranges = (
    df_claims.alias("c")
    .join(
        df_policies.alias("p"),
        (F.col("p.id") == F.col("c.policy_id"))
        & F.col("c.claim_date").between(F.col("p.start_date"), F.coalesce(F.col("p.end_date"), F.lit("2099-12-31").cast("date"))),
        "left",
    )
    .select(
        "c.id",
        "c.policy_id",
        "c.claim_date",
        "c.claimed_amount",
        "c.status",
        "c.claim_type",
        "p.product",
        "p.premium",
    )
)

claim_stats = (
    df_claims
    .groupBy("policy_id")
    .agg(
        F.round(F.avg("approved_amount"), 2).alias("avg_claim_approved_amount"),
        F.round(F.avg("approved_amount"), 2).alias("avg_claim_approved_amount_2"),
    )
)

profiled = (
    joined_ranges.alias("s")
    .join(claim_stats.alias("c"), F.col("c.policy_id") == F.col("s.policy_id"), "left")
    .select("s.*", "c.avg_claim_approved_amount", "c.avg_claim_approved_amount_2")
)

result = (
    profiled
    .select(
        "id",
        "policy_id",
        "status",
        "product",
        "premium",
        "avg_claim_approved_amount",
        "avg_claim_approved_amount_2",
    )
)
