SELECT *
FROM (
    SELECT store_id, CASE WHEN YEAR(last_restock) < 2024 THEN 'before_2024' WHEN YEAR(last_restock) = 2024 THEN '2024' ELSE 'after_2024' END AS last_restock_cohort, COUNT(quantity) AS quantity_count
    FROM inventory
    GROUP BY store_id, CASE WHEN YEAR(last_restock) < 2024 THEN 'before_2024' WHEN YEAR(last_restock) = 2024 THEN '2024' ELSE 'after_2024' END
) AS x
WHERE quantity_count < 8;
