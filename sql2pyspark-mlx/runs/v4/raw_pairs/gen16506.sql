SELECT *
FROM (
    SELECT CASE WHEN YEAR(hire_date) < 2024 THEN 'before_2024' WHEN YEAR(hire_date) = 2024 THEN '2024' ELSE 'after_2024' END AS hire_cohort, COUNT(*) AS num_employees
    FROM employees
    GROUP BY CASE WHEN YEAR(hire_date) < 2024 THEN 'before_2024' WHEN YEAR(hire_date) = 2024 THEN '2024' ELSE 'after_2024' END
) AS t
WHERE num_employees > 9
ORDER BY num_employees, hire_cohort DESC
