SELECT
    CASE WHEN YEAR(last_restock) < 2024 THEN 'before_2024' WHEN YEAR(last_restock) = 2024 THEN '2024' ELSE 'after_2024' END AS last_restock_cohort,
    product_id,
    COUNT(quantity) AS quantity_count,
    MAX(last_restock) AS last_last_restock
FROM inventory
WHERE quantity <= 170 AND quantity = 181
GROUP BY CASE WHEN YEAR(last_restock) < 2024 THEN 'before_2024' WHEN YEAR(last_restock) = 2024 THEN '2024' ELSE 'after_2024' END, product_id
