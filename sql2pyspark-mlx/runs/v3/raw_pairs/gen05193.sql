SELECT CASE WHEN YEAR(c.signup_date) < 2024 THEN 'before_2024' WHEN YEAR(c.signup_date) = 2024 THEN '2024' ELSE 'after_2024' END AS signup_cohort, ROUND(AVG(s.monthly_fee), 2) AS avg_monthly_fee
FROM subscriptions s
INNER JOIN customers c ON c.id = s.customer_id
WHERE c.name IS NULL
GROUP BY CASE WHEN YEAR(c.signup_date) < 2024 THEN 'before_2024' WHEN YEAR(c.signup_date) = 2024 THEN '2024' ELSE 'after_2024' END;
