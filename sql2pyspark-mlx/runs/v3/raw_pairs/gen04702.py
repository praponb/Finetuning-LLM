from pyspark.sql import functions as F

result = (
    df_inventory.alias("i")
    .join(df_store_sales.alias("ss"), (F.col("i.store_id") == F.col("ss.store_id")) & (F.col("i.product_id") == F.col("ss.product_id")), "left")
    .groupBy(
        F.date_format(F.col("ss.sale_date"), "yyyy-MM").alias("sale_month"),
        F.when(F.year(F.col("ss.sale_date")) < 2024, "before_2024").when(F.year(F.col("ss.sale_date")) == 2024, "2024").otherwise("after_2024").alias("sale_cohort"),
    )
    .agg(F.min(F.col("i.quantity")).alias("min_quantity"))
    .orderBy("min_quantity", "sale_month", "sale_cohort")
    .limit(5)
)
