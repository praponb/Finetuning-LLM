SELECT
    CASE WHEN YEAR(last_restock) < 2024 THEN 'before_2024' WHEN YEAR(last_restock) = 2024 THEN '2024' ELSE 'after_2024' END AS last_restock_cohort,
    SUM(quantity) AS total_quantity,
    COUNT(*) AS cnt,
    RANK() OVER (ORDER BY SUM(quantity) DESC) AS quantity_rank
FROM inventory
GROUP BY CASE WHEN YEAR(last_restock) < 2024 THEN 'before_2024' WHEN YEAR(last_restock) = 2024 THEN '2024' ELSE 'after_2024' END;
